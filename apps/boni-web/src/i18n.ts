const dictionaries: Record<Lang, Record<string, string>> = { es, en };

export function translator(lang: Lang): T {
  const dict = dictionaries[lang] ?? es;
  return (key, vars) => {
    // A count of exactly 1 takes the key's ".one" form when there is one ("1 elemento", not "1 elementos").
    const one = vars && Number(vars.n) === 1 ? `${key}.one` : null;
    let s = (one ? (dict[one] ?? es[one as Key]) : undefined) ?? dict[key] ?? es[key as Key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export const KEYS = Object.keys(es) as Key[];

/** A label of the block catalogue (packages/views catalogue.ts, in Spanish) in the interface's language. */
export const catText = (t: T, label: string) => {
  const k = `cat.${label}`;
  const v = t(k);
  return v === k ? label : v;
};
export const missingIn = (lang: Lang) => KEYS.filter((k) => !(k in dictionaries[lang]));
