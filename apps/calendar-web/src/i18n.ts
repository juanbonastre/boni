const dicts: Record<Locale, Record<Key, string>> = { es, en };

let current: Locale = "es";

export function setLocale(l: Locale): void {
  current = l;
  const root = appRoot();
  if (root) root.lang = l;
  else document.documentElement.lang = l;
}

export function t(
  key: Key,
  params?: Record<string, string | number>,
  locale: Locale = current,
): string {
  const raw = dicts[locale][key];
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ""));
}
